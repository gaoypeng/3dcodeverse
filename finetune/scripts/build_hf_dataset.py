def write_parquet(rows, path_prefix, cols=None):
    os.makedirs(os.path.dirname(path_prefix), exist_ok=True)
    n = 0
    for i in range(0, len(rows), SHARD_ROWS):
        chunk = rows[i: i + SHARD_ROWS]
        df = pd.DataFrame(chunk, columns=cols) if cols else pd.DataFrame(chunk)
        suffix = f"-{i // SHARD_ROWS:05d}" if len(rows) > SHARD_ROWS else ""
        df.to_parquet(f"{path_prefix}{suffix}.parquet", index=False, compression="zstd")
        n += 1
    return n


