    # ---- 1. the corpus, sharded by dialect (ShareGPT: conversations + system) ----
    by = collections.defaultdict(list)
    for split in ("train", "val"):
        for l in open(f"{ROOT}/data/md_max/{split}.jsonl"):
            r = json.loads(l)
            msgs = r["messages"]
            by[r["dialect"]].append({
                "id": r["id"], "subset": r["subset"], "caption_type": r["caption"], "split": split,
                "system": msgs[0]["content"],
                "conversations": [{"from": "human", "value": msgs[1]["content"]},
                                  {"from": "gpt", "value": msgs[2]["content"]}],
            })
    for dia, rows in by.items():
        nsh = write_parquet(rows, f"{a.out}/sft/{dia}/train")
        info[f"3dcv_{dia}"] = {"file_name": f"sft/{dia}", "formatting": "sharegpt", "columns": {"messages": "conversations", "system": "system"}}
        stats[f"sft/{dia}"] = {"rows": len(rows), "shards": nsh}
        print(f"[hf] sft/{dia}: {len(rows)} rows, {nsh} shard(s)")

    # ---- 2. the bootstrapped Blender set (execution-verified, generated by our own flywheel) ----
    boot = []
    for l in open(f"{ROOT}/data/sft_v13_boot/train.jsonl"):
        if '"source": "boot_' not in l:
            continue
        m = json.loads(l)["messages"]
        boot.append({"system": m[0]["content"],
                     "conversations": [{"from": "human", "value": m[1]["content"]}, {"from": "gpt", "value": m[2]["content"]}]})
    write_parquet(boot, f"{a.out}/sft/blender_bootstrapped/train")
    info["3dcv_blender_bootstrapped"] = {"file_name": "sft/blender_bootstrapped", "formatting": "sharegpt", "columns": {"messages": "conversations", "system": "system"}}
    stats["sft/blender_bootstrapped"] = {"rows": len(boot), "shards": 1}
    print(f"[hf] sft/blender_bootstrapped: {len(boot)} rows")

    # ---- 3. preference sets ----
    for name, (path, desc) in DPO_SETS.items():
        p = os.path.join(ROOT, path)
        if not os.path.exists(p):
            print(f"[hf] skip {name} (missing)")
            continue
        rows = json.load(open(p))
        write_parquet(rows, f"{a.out}/dpo/{name}")
        info[f"3dcv_dpo_{name}"] = {"file_name": f"dpo/{name}.parquet", "ranking": True, "formatting": "sharegpt",
                                    "columns": {"messages": "conversations", "system": "system", "chosen": "chosen", "rejected": "rejected"}}
